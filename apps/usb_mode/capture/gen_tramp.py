"""Generate the tfshim export list from the real driver's .dynsym.

    python gen_tramp.py driver_sf3500.so OUTDIR

Writes OUTDIR/tfshim_syms.h (names, slot indices, data-object list) and
OUTDIR/tfshim_tramp.S (one MIPS o32 PIC tail-jump trampoline per exported
function, placeholder storage for exported data objects). Only symbol names,
binding, type and size are read from the vendor library.

Each trampoline:
    .cpload $t9                       ; gp from t9 (o32 PIC entry convention)
    lw    $t9, %got(slot_tab)($gp)    ; local GOT page entry
    addiu $t9, $t9, %lo(slot_tab)
    lw    $t9, 4*i($t9)               ; resolved real address (or the missing stub)
    jr    $t9
    addiu $t8, $zero, i               ; delay slot: slot index for the missing stub
a0-a3, the stack, ra, s0-s8, sp and FP registers are untouched; only the
caller-saved t8/t9/gp change, exactly like entering any PIC function.
"""
import os, struct, sys

# Implemented in C by tfshim.c (they forward a0..a3 unchanged).
INTERCEPT = ('video_driver_disp_frame', 'sound_driver_playframe', 'sound_driver_init')

STT = {0: 'NOTYPE', 1: 'OBJECT', 2: 'FUNC', 3: 'SECTION', 4: 'FILE', 6: 'TLS', 10: 'IFUNC'}
STB = {0: 'LOCAL', 1: 'GLOBAL', 2: 'WEAK', 10: 'UNIQUE'}


def read_dynsym(path):
    """Return [(name, type, bind, size, defined)] from .dynsym of a 32-bit LE ELF."""
    d = open(path, 'rb').read()
    if d[:4] != b'\x7fELF' or d[4] != 1 or d[5] != 1:
        raise SystemExit('%s: not a 32-bit little-endian ELF' % path)
    shoff, = struct.unpack_from('<I', d, 0x20)
    shentsize, shnum, _ = struct.unpack_from('<HHH', d, 0x2e)
    sh = [struct.unpack_from('<IIIIIIIIII', d, shoff + i * shentsize) for i in range(shnum)]
    out = []
    for s in sh:
        if s[1] != 11:              # SHT_DYNSYM
            continue
        stroff = sh[s[6]][4]
        for i in range(1, s[5] // 16):
            nm, val, size, info, other, shndx = struct.unpack_from('<IIIBBH', d, s[4] + i * 16)
            name = d[stroff + nm:d.index(b'\0', stroff + nm)].decode()
            out.append((name, STT.get(info & 15, str(info & 15)), STB.get(info >> 4, str(info >> 4)),
                        size, shndx != 0, other & 3))
    return out


def classify(syms):
    funcs, objs, skipped = [], [], []
    for name, typ, bind, size, defined, vis in syms:
        if not defined or not name or bind == 'LOCAL' or vis in (1, 2):
            continue
        if typ == 'FUNC':
            funcs.append((name, bind))
        elif typ == 'OBJECT':
            objs.append((name, bind, size))
        else:
            skipped.append((name, typ))      # linker markers (_end, _gp_disp, ...)
    funcs.sort(); objs.sort()
    return funcs, objs, skipped


def main():
    if len(sys.argv) != 3:
        print(__doc__); return 2
    src, outdir = sys.argv[1], sys.argv[2]
    funcs, objs, skipped = classify(read_dynsym(src))
    tramp = [(n, b) for n, b in funcs if n not in INTERCEPT]
    missing = [n for n in INTERCEPT if n not in [f for f, _ in funcs]]
    if missing:
        raise SystemExit('real driver lacks intercepted functions: %s' % missing)

    h = ['/* SPDX-License-Identifier: MIT */',
         '/* Generated by gen_tramp.py from %s - do not edit. */' % os.path.basename(src),
         '#ifndef TFSHIM_SYMS_H', '#define TFSHIM_SYMS_H', '',
         '#define TFSHIM_NSLOTS %d   /* trampolined functions */' % len(tramp),
         '#define TFSHIM_NEXPORT_FUNCS %d' % len(funcs),
         'static const char *const tfshim_slot_names[TFSHIM_NSLOTS] = {']
    h += ['    "%s",' % n for n, _ in tramp]
    h += ['};', '', '#define TFSHIM_NOBJS %d' % len(objs),
          'static const struct { const char *name; unsigned size; } tfshim_objs[TFSHIM_NOBJS > 0 ? TFSHIM_NOBJS : 1] = {']
    h += ['    { "%s", %d },' % (n, sz) for n, _, sz in objs] or ['    { 0, 0 }']
    h += ['};', '',
          '/* not re-exported (linker markers of the real library): %s */' % ' '.join(n for n, _ in skipped),
          '#endif', '']

    s = ['/* SPDX-License-Identifier: MIT */',
         '/* Generated by gen_tramp.py from %s - do not edit. */' % os.path.basename(src),
         '\t.abicalls', '\t.set noreorder', '\t.set nomacro', '\t.set noat', '',
         '\t.data', '\t.align 2', '\t.globl tfshim_slots', '\t.hidden tfshim_slots',
         '\t.type tfshim_slots,@object',
         'tfshim_slots:', 'tfshim_slot_tab:']
    s += ['\t.word tfshim_missing_asm\t/* %d %s */' % (i, n) for i, (n, _) in enumerate(tramp)]
    s += ['\t.size tfshim_slots, %d' % (4 * len(tramp)), '',
          '\t.text', '\t.align 2', '\t.globl tfshim_missing_asm', '\t.hidden tfshim_missing_asm',
          '\t.type tfshim_missing_asm,@function',
          'tfshim_missing_asm:\t\t/* t8 = slot index; tail-call tfshim_missing(index) */',
          '\t.cpload $25', '\taddu $4, $24, $0', '\tlw $25, %call16(tfshim_missing)($28)',
          '\tjr $25', '\tnop', '\t.size tfshim_missing_asm, .-tfshim_missing_asm', '']
    for i, (n, bind) in enumerate(tramp):
        s += ['\t.%s %s' % ('weak' if bind == 'WEAK' else 'globl', n), '\t.type %s,@function' % n,
              '\t.align 2', '%s:' % n,
              '\t.cpload $25',
              '\tlw $25, %got(tfshim_slot_tab)($28)',
              '\taddiu $25, $25, %lo(tfshim_slot_tab)',
              '\tlw $25, %d($25)' % (4 * i),
              '\tjr $25',
              '\taddiu $24, $0, %d' % i,
              '\t.size %s, .-%s' % (n, n), '']
    if objs:
        s += ['\t/* exported data objects: placeholders, re-pointed at the real', '\t   driver\'s objects by tfshim_alias_objects() at load time */',
              '\t.data']
        for n, bind, sz in objs:
            s += ['\t.%s %s' % ('weak' if bind == 'WEAK' else 'globl', n), '\t.type %s,@object' % n,
                  '\t.align 3', '%s:' % n, '\t.space %d' % max(sz, 1), '\t.size %s, %d' % (n, sz)]
    s.append('')
    open(os.path.join(outdir, 'tfshim_syms.h'), 'w', newline='\n').write('\n'.join(h))
    open(os.path.join(outdir, 'tfshim_tramp.S'), 'w', newline='\n').write('\n'.join(s))
    print('gen_tramp: %d functions (%d trampolines + %d C wrappers), %d data objects, skipped %d markers'
          % (len(funcs), len(tramp), len(INTERCEPT), len(objs), len(skipped)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
